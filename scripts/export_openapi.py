"""Write the API's OpenAPI schema to ``web/openapi.json``, the source of the dashboard's
typed client (``web/lib/api-schema.ts``, generated by ``pnpm --dir web gen:api``).

    python scripts/export_openapi.py            # write it
    python scripts/export_openapi.py --check    # exit 1 if the committed file is stale

The schema comes from the app object, so no server or store is needed. Keys are sorted
and the file ends with a newline, so a regenerated file only differs where the API did.
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Sequence
from pathlib import Path
from typing import Any

from ledgerlens.core.config import repo_path

DEFAULT_OUT = repo_path("web/openapi.json")


def openapi_schema() -> dict[str, Any]:
    from ledgerlens.api.main import create_app

    schema: dict[str, Any] = create_app().openapi()
    return schema


def render(schema: dict[str, Any]) -> str:
    return json.dumps(schema, indent=2, sort_keys=True, ensure_ascii=False) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--out", type=Path, default=DEFAULT_OUT)
    parser.add_argument("--check", action="store_true", help="only compare with --out")
    args = parser.parse_args(argv)
    text = render(openapi_schema())
    if args.check:
        current = args.out.read_text(encoding="utf-8") if args.out.is_file() else ""
        if current != text:
            print(
                f"{args.out} is out of date: run python scripts/export_openapi.py "
                "and pnpm --dir web gen:api",
                file=sys.stderr,
            )
            return 1
        print(f"{args.out} is up to date")
        return 0
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(text, encoding="utf-8", newline="\n")
    print(f"wrote {args.out}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
